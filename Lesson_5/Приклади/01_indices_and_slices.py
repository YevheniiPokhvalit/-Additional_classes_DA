# Для індексації беремо відоме непорожнє слово.
word = "Python"
print("Слово:", word)
print("Довжина:", len(word))
print("Перший символ:", word[0])
print("Останній символ:", word[-1])
print("Від індексу 1 до 4, не включаючи 4:", word[1:4])
print("Перші три символи:", word[:3])
print("Останні два символи:", word[-2:])

# Зрізи працюють також для короткого та порожнього рядка.
short_text = "Я"
empty_text = ""
print(f"Короткий рядок, зріз до 3: [{short_text[:3]}]")
print(f"Порожній рядок, зріз до 3: [{empty_text[:3]}]")
print(f"Порожній рядок, довжина: {len(empty_text)}")
